function showFactory(factoryKey) {
    const info = factories[factoryKey];

    // Защита от ошибки, если передан неверный или пустой ключ
    if (!info) return;

    // Начинаем собирать HTML-контент, выводим заголовок
    let content = `<h2>${info.title || ''}</h2>`;

    // 1. Полное название для главного региона (если есть)
    if (info.fullName) {
        content += `<p class="factory-fullname"><b>Полное название:</b> ${info.fullName}</p>`;
    }

    // 2. Расположение / Местоположение для главного региона
    const location = info.location || info.area;
    if (location && factoryKey !== "moscow") {
        content += `<p class="factory-area"><b>Расположение:</b> ${location}</p>`;
    }

    // 3. Год основания для главного региона
    if (info.established && factoryKey !== "moscow") {
        content += `<p class="factory-established"><b>Год основания:</b> ${info.established}</p>`;
    }

    // 4. Число сотрудников для главного региона
    if (info.employees && factoryKey !== "moscow") {
        content += `<p class="factory-employees"><b>Число сотрудников:</b> ${info.employees}</p>`;
    }

    // 5. Описание (поддерживает и text, и desc)
    const description = info.text || info.desc;
    if (description) {
        content += `<p class="factory-description">${description}</p>`;
    }

    // 6. Главное изображение завода (если есть)
    if (info.image) {
        content += `
            <img src="${info.image}"
                 class="factory-image"
                 alt="${info.title || ''}">
        `;
    }

    // 7. Список моделей для стандартных заводов (ГАЗ, ВАЗ)
    if (info.cars && Array.isArray(info.cars)) {
        content += `
            <h3>Основные модели:</h3>
            <ul>
                ${info.cars.map(car => `<li>${car}</li>`).join("")}
            </ul>
        `;
    }

    // 8. Кнопка "Подробнее" для одиночного завода (если это не Москва)
    if (info.link && factoryKey !== "moscow") {
        content += `<a href="${info.link}" class="more-button">Подробнее</a>`;
    }

    // 9. Карточки подзаводов для Москвы (АЗЛК, ЗИЛ) со всеми их данными
    if (info.plants && Array.isArray(info.plants)) {
        content += `<div class="plants">`;

        content += info.plants.map(plant => {
            let plantHtml = `<div class="plant-card">`;

            // Название завода (АЗЛК / ЗИЛ)
            plantHtml += `<h3>${plant.name || ''}</h3>`;

            // Полное название подзавода
            if (plant.fullName) {
                plantHtml += `<p class="plant-fullname"><b>Полное название:</b> ${plant.fullName}</p>`;
            }

            // Расположение подзавода
            if (plant.location) {
                plantHtml += `<p class="plant-location"><b>Расположение:</b> ${plant.location}</p>`;
            }

            // Год основания подзавода
            if (plant.established) {
                plantHtml += `<p class="plant-established"><b>Год основания:</b> ${plant.established}</p>`;
            }

            // Территория / Площадь подзавода
            if (plant.area) {
                plantHtml += `<p class="plant-area"><b>Территория:</b> ${plant.area}</p>`;
            }

            // Число сотрудников подзавода
            if (plant.employees) {
                plantHtml += `<p class="plant-employees"><b>Число сотрудников:</b> ${plant.employees}</p>`;
            }

            // Описание подзавода
            const plantDesc = plant.desc || plant.text;
            if (plantDesc) {
                plantHtml += `<p class="plant-description">${plantDesc}</p>`;
            }

            // Дополнительная инфа (если осталась)
            if (plant.smallInfo) {
                plantHtml += `<p class="plant-small-info">${plant.smallInfo}</p>`;
            }

            // Ссылка на отдельную страницу подзавода
            if (plant.link) {
                plantHtml += `<a href="${plant.link}" class="more-button">Подробнее</a>`;
            }

            plantHtml += `</div>`;
            return plantHtml;
        }).join("");

        content += `</div>`;
    }

    // Безопасный вывод собранного контента в элемент на странице
    const infoContainer = document.getElementById("factory-info");
    if (infoContainer) {
        infoContainer.innerHTML = content;
    }
}

// Связываем функцию с глобальным объектом window для работы атрибута onclick в HTML
window.showFactory = showFactory;